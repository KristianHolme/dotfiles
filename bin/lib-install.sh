    for plugin in "${plugins[@]}"; do
        plugin_short="${plugin##*:}"
        plugin_short="${plugin_short##*/}"
        if grep -qF "$plugin" <<<"$installed_list" ||
            [[ -d "$HOME/.config/yazi/plugins/${plugin_short}.yazi" ]]; then
            to_upgrade+=("$plugin")
        else
            to_add+=("$plugin")
        fi
    done

    if [[ ${#to_add[@]} -gt 0 ]]; then
        log_info "Installing Yazi plugins: ${to_add[*]}"
        ya pkg add "${to_add[@]}" || log_warning "Some Yazi plugin installs failed (non-critical)"
    fi

