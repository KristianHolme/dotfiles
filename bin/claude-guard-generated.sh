#!/usr/bin/env bash
# Claude Code PreToolUse hook (Edit|Write|MultiEdit): block edits to files that
# dotfiles generates, so a fix lands in the source and survives the next dar/dac.
path="$(jq -r '.tool_input.file_path // empty')"
[[ -n "$path" && -f "$path" ]] || exit 0
head -n 3 "$path" | grep -q 'Generated by dotfiles' || exit 0
echo "Blocked: $path is generated by dotfiles. Edit the source instead: ~/.agents/AGENTS.local.md (this machine) or ~/dotfiles/default/dot-agents/AGENTS.md (all machines), then run: source ~/dotfiles/bin/lib-dotfiles.sh && install_agent_instructions" >&2
exit 2
